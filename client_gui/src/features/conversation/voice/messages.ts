export const VOICE_MESSAGES = { ko, en, ja } as const

/** Merges the voice strings into the global i18n (merging again is harmless). */
export function installVoiceMessages(composer: { mergeLocaleMessage(locale: string, message: Record<string, unknown>): void }): void {
  for (const locale of ['ko', 'en', 'ja'] as const) composer.mergeLocaleMessage(locale, { gui: { voice: VOICE_MESSAGES[locale] } })
}

/** The i18n key of an error code (an unknown code falls back to the generic message). */
export function voiceErrorKey(code: string | null | undefined, has: (key: string) => boolean): string {
  const key = code ? `gui.voice.errors.${code}` : ''
  return key && has(key) ? key : 'gui.voice.errors.failed'
}

/** Human-readable size (MB below 1 GB). */
export function formatBytes(bytes: number): string {
  if (!bytes || bytes < 0) return '0MB'
  const mb = bytes / 1_000_000
  return mb >= 1000 ? `${(mb / 1000).toFixed(1)}GB` : `${Math.max(1, Math.round(mb))}MB`
}

/**
 * F86 — the shown text of a server `unavailable_reason`. The server reason is English (e.g. "This release requires
 * Windows x64"); a known one is shown with its translation key, anything else as sent.
 */
export function voiceReasonText(
  reason: string | null | undefined,
  t: (key: string) => string,
  has: (key: string) => boolean,
): string {
  if (!reason) return ''
  if (/windows/i.test(reason) && has('gui.voice.unavailable_windows')) return t('gui.voice.unavailable_windows')
  return reason
}
