# -*- coding: utf-8 -*-
"""Regenerate the MySQL/MariaDB and PostgreSQL migration sets from the SQLite source.

Group 0088 (TR0007). This is the single, reproducible source of truth for
``server/sql/migrations/{mysql,postgres}``. Re-run it whenever a new SQLite
migration is added so the dialect sets stay in sync.

Two deterministic steps:

  1. ``sqloader convert`` (sqloader==0.2.15) translates each SQLite migration to
     the target dialect (AUTOINCREMENT->AUTO_INCREMENT/SERIAL, INSERT OR IGNORE->
     INSERT IGNORE / ON CONFLICT DO NOTHING, datetime('now')->CURRENT_TIMESTAMP,
     identifier quoting, ...).

  2. Post-process: drop every non-comment ``PRAGMA ...`` statement line.

Why step 2 exists (sqloader 0.2.15 convert defect, see TR0007 §2-2): the converter
does NOT reliably remove ``PRAGMA foreign_keys`` on non-SQLite targets. ``= OFF``
variants are left verbatim, and a following INSERT's idempotency clause can be
mis-attached to the PRAGMA, producing broken statements such as
``PRAGMA foreign_keys = OFF ON CONFLICT DO NOTHING;``. PRAGMA is SQLite-only, so
removing these whole lines is the correct fix.

Lossless proof (TR0007 §2-2, finding #4): dropping the PRAGMA *line* never strips a
real INSERT's conflict handling, because each seed INSERT carries its own
IGNORE / ON CONFLICT clause on its own statement. ``--verify`` re-checks this
statement-by-statement across all files before writing. The mis-attached clause on
a PRAGMA line is a *duplicate* of the converter's already-correct clause on the
real INSERT, so deleting the PRAGMA line removes only the duplicate.

Usage (run from server/):
    python tools/regen_dialect_migrations.py            # regenerate in place
    python tools/regen_dialect_migrations.py --verify   # regenerate to temp + diff, no write
"""
